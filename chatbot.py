"""WOC7015 reference chatbot: core module.

One class, one log format. Every call to Chatbot.ask() appends one row to a CSV log,
so results from all candidates can be pooled.

Settings come from a configuration card (cards/Cxx.json):
    candidate_id, topic, temperature, seed, memory ("on" or "off")
Do not edit the card. Do not edit this file before you have recorded the commit hash.
"""
import csv
import datetime
import json
import os
import subprocess
import time
import uuid

MODEL = "llama-3.3-70b-versatile"
MIN_INTERVAL_S = 2.2          # keeps you under 30 requests per minute (Groq free tier, check console)
MAX_RETRIES = 6
HERE = os.path.dirname(os.path.abspath(__file__))

LOG_COLUMNS = [
    "candidate_id", "run_id", "timestamp_utc", "commit_hash", "model",
    "topic", "temperature", "seed", "memory",
    "test_type",        # red_team | metamorphic | ai_generated | manual
    "category",         # red_team: injection | harmful | leakage | role_override; metamorphic: MR1.. ; else free text
    "prompt_id", "pair_id", "role",   # pair_id + role (source | followup) for metamorphic tests
    "run_number", "session_id", "turn_number",
    "prompt", "response",
    "label",            # YOU fill in: 1 = attack succeeded / relation violated / test failed, 0 = not
    "label_reason",     # YOU fill in: one line, tied to your written success definition
    "audit_verdict",    # YOU fill in for ai_generated rows: correct | wrong | hallucinated | duplicate
    "rater2_label",     # second rater's label on a 10% sample
    "latency_ms", "prompt_tokens", "completion_tokens", "error",
]


def _load_env():
    path = os.path.join(HERE, ".env")
    if os.path.exists(path):
        for line in open(path, encoding="utf8"):
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                os.environ.setdefault(k.strip(), v.strip().strip('"').strip("'"))


_load_env()


def load_card(path):
    with open(path, encoding="utf8") as f:
        card = json.load(f)
    for key in ("candidate_id", "topic", "temperature", "seed", "memory"):
        if key not in card:
            raise ValueError(f"card {path} is missing '{key}'")
    if card["memory"] not in ("on", "off"):
        raise ValueError("memory must be 'on' or 'off'")
    return card


def load_system_prompt(topic):
    path = os.path.join(HERE, "system_prompts", f"{topic}.txt")
    with open(path, encoding="utf8") as f:
        return f.read().strip()


def commit_hash():
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=HERE,
                             capture_output=True, text=True, timeout=5)
        return out.stdout.strip() or "unknown"
    except Exception:
        return "unknown"


class DryRunClient:
    """Stub used by --dry-run so the pipeline can be tested without an API key."""

    def complete(self, messages, temperature, seed):
        last = messages[-1]["content"]
        return {"text": f"[dry-run reply to: {last[:60]}]", "prompt_tokens": 0, "completion_tokens": 0}


class GroqClient:
    def __init__(self):
        key = os.environ.get("GROQ_API_KEY")
        if not key:
            raise RuntimeError("Set GROQ_API_KEY (copy .env.example to .env, or export it).")
        from groq import Groq          # imported here so --dry-run needs no packages
        import groq
        self._groq = groq
        self._client = Groq(api_key=key)

    def complete(self, messages, temperature, seed):
        delay = 5
        for attempt in range(MAX_RETRIES):
            try:
                r = self._client.chat.completions.create(
                    model=MODEL, messages=messages, temperature=temperature, seed=seed, max_tokens=512)
                return {"text": r.choices[0].message.content,
                        "prompt_tokens": r.usage.prompt_tokens,
                        "completion_tokens": r.usage.completion_tokens}
            except self._groq.RateLimitError:
                time.sleep(delay)
                delay = min(delay * 2, 60)
        raise RuntimeError("rate limit: gave up after retries; wait and re-run the missing rows")


class Chatbot:
    def __init__(self, card, log_path, client=None):
        self.card = card
        self.system_prompt = load_system_prompt(card["topic"])
        self.client = client or GroqClient()
        self.log_path = log_path
        self.commit = commit_hash()
        if self.commit == "unknown":
            print("WARNING: commit hash unknown. Use git clone and git checkout v1.0, not Download ZIP.")
        self._last_call = 0.0
        self.new_session()
        os.makedirs(os.path.dirname(os.path.abspath(log_path)), exist_ok=True)
        if not os.path.exists(log_path):
            with open(log_path, "w", newline="", encoding="utf8") as f:
                csv.DictWriter(f, fieldnames=LOG_COLUMNS).writeheader()

    def new_session(self):
        self.session_id = uuid.uuid4().hex[:8]
        self.history = []          # list of {"role","content"}; used only when memory is on
        self.turn = 0

    def ask(self, prompt, *, test_type="manual", category="", prompt_id="", pair_id="", role="",
            run_number=1, seed=None):
        """Send one user turn. Returns the reply text. Logs one row."""
        wait = MIN_INTERVAL_S - (time.time() - self._last_call)
        if wait > 0:
            time.sleep(wait)
        self.turn += 1
        if self.card["memory"] == "on":
            messages = [{"role": "system", "content": self.system_prompt}] + self.history + \
                       [{"role": "user", "content": prompt}]
        else:
            messages = [{"role": "system", "content": self.system_prompt},
                        {"role": "user", "content": prompt}]
        use_seed = self.card["seed"] if seed is None else seed
        t0 = time.time()
        error, res = "", {"text": "", "prompt_tokens": "", "completion_tokens": ""}
        try:
            res = self.client.complete(messages, self.card["temperature"], use_seed)
        except Exception as e:           # log the failure, keep the batch going
            error = str(e)[:200]
        self._last_call = time.time()
        if self.card["memory"] == "on" and not error:
            self.history += [{"role": "user", "content": prompt},
                             {"role": "assistant", "content": res["text"]}]
        row = {
            "candidate_id": self.card["candidate_id"], "run_id": uuid.uuid4().hex[:10],
            "timestamp_utc": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "commit_hash": self.commit, "model": MODEL,
            "topic": self.card["topic"], "temperature": self.card["temperature"],
            "seed": use_seed, "memory": self.card["memory"],
            "test_type": test_type, "category": category, "prompt_id": prompt_id,
            "pair_id": pair_id, "role": role, "run_number": run_number,
            "session_id": self.session_id, "turn_number": self.turn,
            "prompt": prompt, "response": res["text"],
            "label": "", "label_reason": "", "audit_verdict": "", "rater2_label": "",
            "latency_ms": int((self._last_call - t0) * 1000),
            "prompt_tokens": res["prompt_tokens"], "completion_tokens": res["completion_tokens"],
            "error": error,
        }
        with open(self.log_path, "a", newline="", encoding="utf8") as f:
            csv.DictWriter(f, fieldnames=LOG_COLUMNS).writerow(row)
        return res["text"]
